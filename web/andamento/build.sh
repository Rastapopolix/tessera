# Andamento's virtual prototype: Tessera's core at 48 kHz with Andamento's panel UI (web/andamento/sim.c) to
# WebAssembly, and one page that holds everything (build/andamento/index.html, with the worklet and the wasm inside
# it), so it opens from any server or as a published page.
#   web/andamento/build.sh        (needs Emscripten's emcc, on the PATH or in ~/emsdk, and Python 3)
#   web/andamento/build.sh --headers   only the generated headers in build/andamento/gen (tests/run_tests.sh's
#                                      and_keys job builds sim.c for the PC from them)
set -e
cd "$(dirname "$0")/../.."
OUT=build/andamento
GEN=$OUT/gen
mkdir -p "$GEN"
# the generated headers as tools/build.py makes them (without the JieLi toolchain), then the tables at the Seed's
# 48 kHz in a folder of their own (platform/daisy/Makefile does the same)
[ -f build/gen/ui_fonts.h ] || python3 -c "import sys; sys.path.insert(0, 'tools'); import build; build.generate()"
cp build/gen/*.h "$GEN/"
MELODEE_FS=48000 python3 tools/gen_tables.py "$GEN/melodee_tables.h"
python3 tools/gen_909_tables.py "$GEN/x0x_drum_tables.h"
python3 - "$GEN/sim_demos.h" <<'PY'
import sys
from pathlib import Path
out = ["/* Generated by web/andamento/build.sh from demos/*.tsp: slots A and B */"]
for name, f in (("SIM_DEMO_A", "still-tide"), ("SIM_DEMO_B", "koto-garden")):
    b = Path(f"demos/{f}.tsp").read_bytes()
    out.append(f"static const uint8_t {name}[{len(b)}] = {{" + ",".join(str(x) for x in b) + "};")
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
PY
[ "$1" = --headers ] && exit 0
command -v emcc >/dev/null 2>&1 || PATH="${EMSDK:-$HOME/emsdk}/upstream/emscripten:$PATH"
command -v emcc >/dev/null 2>&1 || { echo "emcc not found: install Emscripten (emsdk)"; exit 1; }
# as web/sim/build.sh: no fused multiply-adds, a 1 MiB stack, no file system; the device's engine set; no screen
# reader (Andamento's UI does not speak yet)
emcc -O2 -ffp-contract=off -w -DMELODEE_USB_AUDIO=1 -DMELODEE_ACCESS=0 -DMELODEE_LOOK=1 -DMELODEE_FM6=1 -DMELODEE_PHYS=1 \
    "-DMELODEE_VERSION=\"andamento web\"" -I"$GEN" -Ifirmware/src -Itests \
    --no-entry -sSTANDALONE_WASM -sSTACK_SIZE=1048576 -sINITIAL_MEMORY=33554432 -sFILESYSTEM=0 \
    -o "$OUT/andamento.wasm" web/andamento/sim.c
# the page: index.html with the worklet and the wasm (base64) put in
python3 - "$OUT" <<'PY'
import base64, sys
from pathlib import Path
out = Path(sys.argv[1])
page = Path("web/andamento/index.html").read_text()
page = page.replace("@WORKLET@", Path("web/andamento/worklet.js").read_text().replace("</script", "<\\/script"))
page = page.replace("@WASM@", base64.b64encode((out / "andamento.wasm").read_bytes()).decode())
(out / "andamento.html").write_text(page)          # (the body alone: what gets published)
(out / "index.html").write_text('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n</head>\n<body>\n'
    + page + '</body>\n</html>\n')
PY
echo "andamento  $OUT/andamento.wasm  $(wc -c < "$OUT/andamento.wasm") B;  $OUT/index.html  $(wc -c < "$OUT/index.html") B"
