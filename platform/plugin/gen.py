"""The generated headers the plugin's core needs, in build/gen/ (as ./build.sh and web/sim/build.sh make them):
UI fonts, icons, palettes, tables, the 909 tables, the two demos the simulator starts with and every demo as a
factory preset (plugin_demos.h); and core_syms.h, the
names every private copy of the core renames (core_copy.c: one copy per plugin instance). Run from anywhere;
CMakeLists.txt runs it at configure time. core_syms.h needs clang and nm (or llvm-nm): the core is compiled once,
with the plugin's options (core_defs.txt), and its defined global symbols listed."""
import os
import platform
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

os.environ["PYTHONUTF8"] = "1"   # the generators read UTF-8 sources; Windows' default code page cannot
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import build  # noqa: E402  (tools/build.py)

build.generate()
gen = ROOT / "build" / "gen"
subprocess.run([sys.executable, str(ROOT / "tools" / "gen_909_tables.py"), str(gen / "x0x_drum_tables.h")], check=True)
out = ["/* Generated by platform/plugin/gen.py from demos/*.tsp: slots A and B, as web/sim/build.sh makes them */"]
for name, f in (("SIM_DEMO_A", "still-tide"), ("SIM_DEMO_B", "koto-garden")):
    b = (ROOT / "demos" / f"{f}.tsp").read_bytes()
    out.append(f"static const uint8_t {name}[{len(b)}] = {{" + ",".join(str(x) for x in b) + "};")
(gen / "sim_demos.h").write_text("\n".join(out) + "\n")
# every demo, for the DAW's preset browser (presets.cpp): its file name (the load key) and its record
out = ["/* Generated by platform/plugin/gen.py from demos/*.tsp: the plugin's factory presets (presets.cpp) */"]
demos = sorted((ROOT / "demos").glob("*.tsp"))
for i, f in enumerate(demos):
    out.append(f"static const uint8_t PLUGIN_DEMO_{i}[{f.stat().st_size}] = {{" + ",".join(str(x) for x in f.read_bytes()) + "};")
good = {}   # demos/README.md's table: each file's "Good for", the preset's description
for line in (ROOT / "demos" / "README.md").read_text().splitlines():
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    if len(cells) >= 3 and cells[0].startswith("`") and cells[0].endswith(".tsp`"):
        good[cells[0].strip("`")[:-4]] = cells[2].replace("\\", "\\\\").replace('"', '\\"')
out.append("static const struct { const char *key; const uint8_t *data; unsigned size; const char *about; } PLUGIN_DEMOS[] = {")
out += [f'    {{"{f.stem}", PLUGIN_DEMO_{i}, sizeof PLUGIN_DEMO_{i}, "{good.get(f.stem, "")}"}},' for i, f in enumerate(demos)]
out.append("};")
(gen / "plugin_demos.h").write_text("\n".join(out) + "\n")


def core_syms():
    """build/gen/core_syms.h: '#define name TESS_NS(name)' for each global the core defines (functions and data), so
    that each copy (core_copy.c, compiled with its own TESS_PFX) has names of its own. The file-level statics are the
    copy's own anyway (one translation unit each)."""
    here = ROOT / "platform" / "plugin"
    cc = os.environ.get("CC") or shutil.which("clang")
    nm = shutil.which("llvm-nm") or shutil.which("nm")
    if not cc or not nm:
        sys.exit("plugin: gen.py needs clang and nm (or llvm-nm) for build/gen/core_syms.h")
    defs = [l.strip() for l in (here / "core_defs.txt").read_text().splitlines() if l.strip()]
    with tempfile.TemporaryDirectory() as d:
        obj = Path(d) / "core.o"
        cmd = [cc, "-c", "-O0", "-w", "-ffp-contract=off", "-fvisibility=hidden", "-o", str(obj)]
        cmd += ["-D" + x for x in defs]
        cmd += ["-I" + str(p) for p in (here, ROOT / "platform" / "core", gen, ROOT / "firmware" / "src")]
        cmd.append(str(ROOT / "web" / "sim" / "sim.c"))
        subprocess.run(cmd, check=True)
        names = subprocess.run([nm, "-g", "--defined-only", "-j", str(obj)], check=True, capture_output=True,
                               text=True).stdout.split()
    if platform.system() == "Darwin":   # (Mach-O: C names have a leading underscore)
        names = [n[1:] for n in names if n.startswith("_")]
    names = sorted(set(n for n in names if n and n != "main" and not n.startswith(".")))
    lines = ["/* Generated by platform/plugin/gen.py: the core's defined global symbols (web/sim/sim.c, built with",
             " * core_defs.txt), each renamed to TESS_NS(name) in a private copy of the core (core_copy.c) */"]
    lines += [f"#define {n} TESS_NS({n})" for n in names]
    (gen / "core_syms.h").write_text("\n".join(lines) + "\n")
    print(f"plugin: {len(names)} core symbols in {gen / 'core_syms.h'}")


core_syms()
print(f"plugin: generated headers in {gen}")
