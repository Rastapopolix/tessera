"""The generated headers the plugin's core needs, in build/gen/ (as ./build.sh and web/sim/build.sh make them):
UI fonts, icons, palettes, tables, the 909 tables and the two demos the simulator starts with. Run from anywhere;
CMakeLists.txt runs it at configure time."""
import os
import subprocess
import sys
from pathlib import Path

os.environ["PYTHONUTF8"] = "1"   # the generators read UTF-8 sources; Windows' default code page cannot
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import build  # noqa: E402  (tools/build.py)

build.generate()
gen = ROOT / "build" / "gen"
subprocess.run([sys.executable, str(ROOT / "tools" / "gen_909_tables.py"), str(gen / "x0x_drum_tables.h")], check=True)
out = ["/* Generated by platform/plugin/gen.py from demos/*.tsp: slots A and B, as web/sim/build.sh makes them */"]
for name, f in (("SIM_DEMO_A", "still-tide"), ("SIM_DEMO_B", "koto-garden")):
    b = (ROOT / "demos" / f"{f}.tsp").read_bytes()
    out.append(f"static const uint8_t {name}[{len(b)}] = {{" + ",".join(str(x) for x in b) + "};")
(gen / "sim_demos.h").write_text("\n".join(out) + "\n")
print(f"plugin: generated headers in {gen}")
