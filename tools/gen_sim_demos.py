"""The demo projects (demos/*.tsp) as C arrays, for the host builds that start with them (web/sim/sim.c,
web/rfm1/core_tessera.c): STILL TIDE in slot A, KOTO GARDEN in slot B.
  tools/gen_sim_demos.py build/gen/sim_demos.h"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
out = ["/* Generated by tools/gen_sim_demos.py from demos/*.tsp: the simulator's slots A and B */"]
for name, f in (("SIM_DEMO_A", "still-tide"), ("SIM_DEMO_B", "koto-garden")):
    b = (ROOT / "demos" / f"{f}.tsp").read_bytes()
    out.append(f"static const uint8_t {name}[{len(b)}] = {{" + ",".join(str(x) for x in b) + "};")
Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "build/gen/sim_demos.h").write_text("\n".join(out) + "\n")
